//! Build step for the local control API: reads the commands registered with
//! `tauri::generate_handler![...]` in `src/lib.rs`, finds each one's `#[tauri::command]` function,
//! and writes `$OUT_DIR/control_registry.rs` with every command's name, documentation, injected
//! context and parameters (with a JSON Schema for each). It also lists the event names the backend
//! emits. Nothing here is written by hand: a command added to the handler list shows up in the API
//! on the next build, with its parameters.

use std::collections::{BTreeMap, BTreeSet, HashMap};
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use quote::ToTokens;
use serde_json::{json, Map, Value};
use syn::punctuated::Punctuated;
use syn::visit::Visit;

/// Types the Tauri command macro fills in itself rather than reading from the call's arguments.
const INJECTED: &[&str] = &["State", "AppHandle", "Window", "WebviewWindow", "Webview", "Request", "Invoke", "InvokeMessage", "CommandScope", "GlobalScope", "Channel"];

struct Param {
    key: String,
    rust_name: String,
    rust_type: String,
    required: bool,
    schema: Value,
}

struct Command {
    name: String,
    path: String,
    module: String,
    doc: String,
    is_async: bool,
    injected: Vec<String>,
    params: Vec<Param>,
    returns: String,
    found: bool,
}

struct FnInfo {
    module: String,
    item: syn::ItemFn,
}

#[derive(Clone)]
struct StructInfo {
    item: syn::ItemStruct,
}

pub fn generate(src_dir: &Path, out_file: &Path) {
    println!("cargo:rerun-if-changed={}", src_dir.display());
    let mut files: Vec<(String, syn::File)> = vec![];
    let mut entries: Vec<PathBuf> = std::fs::read_dir(src_dir).expect("src dir").flatten().map(|e| e.path()).filter(|p| p.extension().is_some_and(|x| x == "rs")).collect();
    entries.sort();
    for p in entries {
        let module = p.file_stem().unwrap().to_string_lossy().to_string();
        let text = std::fs::read_to_string(&p).expect("read source");
        let parsed = syn::parse_file(&text).unwrap_or_else(|e| panic!("control registry: can't parse {}: {e}", p.display()));
        files.push((module, parsed));
    }

    // The handler list, exactly as registered.
    let lib = &files.iter().find(|(m, _)| m == "lib").expect("lib.rs").1;
    let mut finder = HandlerFinder { paths: vec![] };
    finder.visit_file(lib);
    assert!(!finder.paths.is_empty(), "control registry: no tauri::generate_handler![..] found in lib.rs");

    // Every #[tauri::command] function and every struct, by module.
    let mut fns: HashMap<String, Vec<FnInfo>> = HashMap::new();
    let mut structs: HashMap<String, StructInfo> = HashMap::new();
    let mut events: BTreeSet<String> = BTreeSet::new();
    for (module, f) in &files {
        collect_items(module, &f.items, &mut fns, &mut structs);
        let mut ev = EventFinder { names: &mut events };
        ev.visit_file(f);
    }

    let mut commands = vec![];
    for path in &finder.paths {
        let segs: Vec<String> = path.segments.iter().map(|s| s.ident.to_string()).collect();
        let name = segs.last().unwrap().clone();
        let want_module = if segs.len() > 1 { segs[segs.len() - 2].clone() } else { "lib".to_string() };
        let candidates = fns.get(&name).map(|v| v.iter().collect::<Vec<_>>()).unwrap_or_default();
        let pick = candidates.iter().find(|f| f.module == want_module).or_else(|| if candidates.len() == 1 { candidates.first() } else { None });
        match pick {
            Some(f) => commands.push(describe(&name, &segs.join("::"), f, &structs)),
            None => {
                println!("cargo:warning=control registry: no #[tauri::command] fn found for `{}`; its parameters are unknown", segs.join("::"));
                commands.push(Command { name: name.clone(), path: segs.join("::"), module: want_module, doc: String::new(), is_async: false, injected: vec![], params: vec![], returns: String::new(), found: false });
            }
        }
    }

    let mut out = String::new();
    out.push_str("// @generated by build/control_registry.rs from the commands registered in src/lib.rs. Do not edit.\n");
    out.push_str("pub static COMMANDS: &[CommandSpec] = &[\n");
    for c in &commands {
        let _ = write!(
            out,
            "    CommandSpec {{ name: {:?}, path: {:?}, module: {:?}, doc: {:?}, is_async: {}, injected: &[{}], params: &[",
            c.name,
            c.path,
            c.module,
            c.doc,
            c.is_async,
            c.injected.iter().map(|s| format!("{s:?}")).collect::<Vec<_>>().join(", ")
        );
        for p in &c.params {
            let _ = write!(out, "ParamSpec {{ key: {:?}, rust_name: {:?}, rust_type: {:?}, required: {}, schema: {:?} }}, ", p.key, p.rust_name, p.rust_type, p.required, p.schema.to_string());
        }
        let _ = writeln!(out, "], returns: {:?}, signature_found: {} }},", c.returns, c.found);
    }
    out.push_str("];\n");
    out.push_str("pub static EVENTS: &[&str] = &[");
    out.push_str(&events.iter().map(|e| format!("{e:?}")).collect::<Vec<_>>().join(", "));
    out.push_str("];\n");
    std::fs::write(out_file, out).expect("write control registry");
}

struct HandlerFinder {
    paths: Vec<syn::Path>,
}

impl<'ast> Visit<'ast> for HandlerFinder {
    fn visit_macro(&mut self, m: &'ast syn::Macro) {
        if m.path.segments.last().is_some_and(|s| s.ident == "generate_handler") {
            let list = m.parse_body_with(Punctuated::<syn::Path, syn::Token![,]>::parse_terminated).expect("control registry: generate_handler list");
            self.paths.extend(list);
        }
        syn::visit::visit_macro(self, m);
    }
}

/// `x.emit("name", ..)` and `x.emit_to(target, "name", ..)`, wherever they are.
struct EventFinder<'a> {
    names: &'a mut BTreeSet<String>,
}

impl<'ast> Visit<'ast> for EventFinder<'_> {
    fn visit_expr_method_call(&mut self, c: &'ast syn::ExprMethodCall) {
        let at = match c.method.to_string().as_str() {
            "emit" => Some(0),
            "emit_to" => Some(1),
            _ => None,
        };
        if let Some(syn::Expr::Lit(syn::ExprLit { lit: syn::Lit::Str(s), .. })) = at.and_then(|i| c.args.iter().nth(i)) {
            self.names.insert(s.value());
        }
        syn::visit::visit_expr_method_call(self, c);
    }
}

fn collect_items(module: &str, items: &[syn::Item], fns: &mut HashMap<String, Vec<FnInfo>>, structs: &mut HashMap<String, StructInfo>) {
    for it in items {
        match it {
            syn::Item::Fn(f) if f.attrs.iter().any(is_command_attr) => {
                fns.entry(f.sig.ident.to_string()).or_default().push(FnInfo { module: module.to_string(), item: f.clone() });
            }
            syn::Item::Struct(s) => {
                structs.entry(s.ident.to_string()).or_insert(StructInfo { item: s.clone() });
            }
            syn::Item::Mod(m) if m.ident != "tests" => {
                if let Some((_, inner)) = &m.content {
                    collect_items(module, inner, fns, structs);
                }
            }
            _ => {}
        }
    }
}

fn is_command_attr(a: &syn::Attribute) -> bool {
    let segs: Vec<String> = a.path().segments.iter().map(|s| s.ident.to_string()).collect();
    segs == ["tauri", "command"] || segs == ["command"]
}

fn docs(attrs: &[syn::Attribute]) -> String {
    let mut lines = vec![];
    for a in attrs {
        if !a.path().is_ident("doc") {
            continue;
        }
        if let syn::Meta::NameValue(nv) = &a.meta {
            if let syn::Expr::Lit(syn::ExprLit { lit: syn::Lit::Str(s), .. }) = &nv.value {
                lines.push(s.value().trim().to_string());
            }
        }
    }
    lines.join(" ").trim().to_string()
}

fn type_string(t: &syn::Type) -> String {
    t.to_token_stream().to_string().replace(" < ", "<").replace("< ", "<").replace(" >", ">").replace(" , ", ", ").replace(" :: ", "::").replace("& ", "&").replace(" '", " '")
}

/// Tauri's default argument naming: the Rust name in lowerCamelCase.
fn camel(s: &str) -> String {
    let mut out = String::new();
    let mut up = false;
    for (i, ch) in s.chars().enumerate() {
        if ch == '_' {
            up = i > 0;
            continue;
        }
        if up {
            out.extend(ch.to_uppercase());
            up = false;
        } else {
            out.push(ch);
        }
    }
    out
}

fn last_ident(t: &syn::Type) -> Option<(String, Option<&syn::PathArguments>)> {
    match t {
        syn::Type::Path(p) => p.path.segments.last().map(|s| (s.ident.to_string(), Some(&s.arguments))),
        syn::Type::Reference(r) => last_ident(&r.elem),
        _ => None,
    }
}

fn generic_args(args: Option<&syn::PathArguments>) -> Vec<syn::Type> {
    match args {
        Some(syn::PathArguments::AngleBracketed(a)) => a
            .args
            .iter()
            .filter_map(|g| match g {
                syn::GenericArgument::Type(t) => Some(t.clone()),
                _ => None,
            })
            .collect(),
        _ => vec![],
    }
}

fn describe(name: &str, path: &str, f: &FnInfo, structs: &HashMap<String, StructInfo>) -> Command {
    let item = &f.item;
    let attr_async = item.attrs.iter().filter(|a| is_command_attr(a)).any(|a| a.to_token_stream().to_string().contains("async"));
    let mut injected = vec![];
    let mut params = vec![];
    for arg in &item.sig.inputs {
        let syn::FnArg::Typed(pt) = arg else { continue };
        let rust_name = match &*pt.pat {
            syn::Pat::Ident(i) => i.ident.to_string(),
            other => other.to_token_stream().to_string(),
        };
        let ty = &*pt.ty;
        let (head, _) = last_ident(ty).unwrap_or_default();
        if INJECTED.contains(&head.as_str()) {
            injected.push(type_string(ty));
            continue;
        }
        let (schema, optional) = schema_for(ty, structs, 0);
        params.push(Param { key: camel(&rust_name), rust_name, rust_type: type_string(ty), required: !optional, schema });
    }
    let returns = match &item.sig.output {
        syn::ReturnType::Default => "()".to_string(),
        syn::ReturnType::Type(_, t) => type_string(t),
    };
    Command { name: name.to_string(), path: path.to_string(), module: f.module.clone(), doc: docs(&item.attrs), is_async: item.sig.asyncness.is_some() || attr_async, injected, params, returns, found: true }
}

/// A JSON Schema for a Rust type, and whether a missing value is fine (Option).
fn schema_for(t: &syn::Type, structs: &HashMap<String, StructInfo>, depth: usize) -> (Value, bool) {
    let Some((head, args)) = last_ident(t) else { return (json!({}), false) };
    let gen = generic_args(args);
    let s = match head.as_str() {
        "Option" => {
            // Optional (may be left out) and nullable: None is sent and read back as null, as in
            // get_state.settings (lighter, minimize_playing).
            let inner = gen.first().map(|g| schema_for(g, structs, depth).0).unwrap_or(json!({}));
            return (nullable(inner), true);
        }
        "String" | "str" | "PathBuf" | "Path" | "OsString" | "Cow" => json!({"type": "string"}),
        "bool" => json!({"type": "boolean"}),
        "u8" | "u16" | "u32" | "u64" | "u128" | "usize" => json!({"type": "integer", "minimum": 0}),
        "i8" | "i16" | "i32" | "i64" | "i128" | "isize" => json!({"type": "integer"}),
        "f32" | "f64" => json!({"type": "number"}),
        "Value" => json!({}),
        "Vec" | "HashSet" | "BTreeSet" | "VecDeque" => {
            let inner = gen.first().map(|g| schema_for(g, structs, depth).0).unwrap_or(json!({}));
            json!({"type": "array", "items": inner})
        }
        "HashMap" | "BTreeMap" => {
            let inner = gen.get(1).map(|g| schema_for(g, structs, depth).0).unwrap_or(json!({}));
            json!({"type": "object", "additionalProperties": inner})
        }
        other => match structs.get(other) {
            Some(si) if depth < 4 => struct_schema(other, &si.item, structs, depth + 1),
            _ => json!({"type": "object", "description": format!("Rust type {other}")}),
        },
    };
    (s, false)
}

/// The schema with null allowed too: `type` becomes a list with "null" in it. A schema with no
/// type already allows anything, null included.
fn nullable(mut s: Value) -> Value {
    let null = Value::String("null".into());
    match s.get("type").cloned() {
        Some(Value::String(t)) if t != "null" => s["type"] = json!([t, "null"]),
        Some(Value::Array(mut ts)) if !ts.contains(&null) => {
            ts.push(null);
            s["type"] = Value::Array(ts);
        }
        Some(_) => {}
        None if s.get("anyOf").is_some() || s.get("enum").is_some() => s = json!({"anyOf": [s, {"type": "null"}]}),
        None => {}
    }
    s
}

fn serde_meta(attrs: &[syn::Attribute]) -> BTreeMap<String, Option<String>> {
    let mut out = BTreeMap::new();
    for a in attrs.iter().filter(|a| a.path().is_ident("serde")) {
        let _ = a.parse_nested_meta(|m| {
            let key = m.path.get_ident().map(|i| i.to_string()).unwrap_or_default();
            let val = if m.input.peek(syn::Token![=]) {
                let v: syn::Expr = m.value()?.parse()?;
                match v {
                    syn::Expr::Lit(syn::ExprLit { lit: syn::Lit::Str(s), .. }) => Some(s.value()),
                    other => Some(other.to_token_stream().to_string()),
                }
            } else {
                if m.input.peek(syn::token::Paren) {
                    let content;
                    syn::parenthesized!(content in m.input);
                    let _: proc_macro2::TokenStream = content.parse()?;
                }
                None
            };
            out.insert(key, val);
            Ok(())
        });
    }
    out
}

fn rename(name: &str, rule: Option<&str>) -> String {
    match rule {
        Some("camelCase") => camel(name),
        Some("lowercase") => name.to_lowercase(),
        Some("UPPERCASE") => name.to_uppercase(),
        Some("kebab-case") => name.replace('_', "-"),
        Some("PascalCase") => {
            let c = camel(name);
            let mut ch = c.chars();
            ch.next().map(|f| f.to_uppercase().collect::<String>() + ch.as_str()).unwrap_or_default()
        }
        _ => name.to_string(),
    }
}

fn struct_schema(name: &str, s: &syn::ItemStruct, structs: &HashMap<String, StructInfo>, depth: usize) -> Value {
    let derives = s.attrs.iter().filter(|a| a.path().is_ident("derive")).map(|a| a.to_token_stream().to_string()).collect::<String>();
    if !derives.contains("Deserialize") {
        return json!({"type": "object", "description": format!("Rust type {name}")});
    }
    let top = serde_meta(&s.attrs);
    let all_default = top.contains_key("default");
    let rule = top.get("rename_all").cloned().flatten();
    let mut props = Map::new();
    let mut required = vec![];
    // Serde ignores fields it doesn't know unless the struct says otherwise.
    let open = !top.contains_key("deny_unknown_fields");
    if let syn::Fields::Named(named) = &s.fields {
        for f in &named.named {
            let meta = serde_meta(&f.attrs);
            if meta.contains_key("skip") || meta.contains_key("skip_deserializing") {
                continue;
            }
            if meta.contains_key("flatten") {
                continue;
            }
            let rust = f.ident.as_ref().map(|i| i.to_string()).unwrap_or_default();
            let key = meta.get("rename").cloned().flatten().unwrap_or_else(|| rename(&rust, rule.as_deref()));
            let (mut fs, optional) = schema_for(&f.ty, structs, depth);
            let d = docs(&f.attrs);
            if !d.is_empty() {
                if let Some(o) = fs.as_object_mut() {
                    o.entry("description").or_insert(Value::String(d));
                }
            }
            if !(optional || all_default || meta.contains_key("default")) {
                required.push(Value::String(key.clone()));
            }
            props.insert(key, fs);
        }
    }
    let mut o = json!({"type": "object", "title": name, "properties": props, "additionalProperties": open});
    let d = docs(&s.attrs);
    if !d.is_empty() {
        o["description"] = Value::String(d);
    }
    if !required.is_empty() {
        o["required"] = Value::Array(required);
    }
    o
}
